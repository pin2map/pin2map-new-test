import assert from "node:assert/strict";
import {createRequire} from "node:module";
const require=createRequire(import.meta.url);
const ops=require("../application/pin-operations.js");
const domain=require("../domain/project-model.js");
const project=domain.defaultProject();
const deps={validatePosition:domain.position,cleanText:domain.cleanText};
const pin=ops.createPin(project,{id:"p1",lat:48.7758,lng:9.1829,name:"  Stuttgart  ",layerId:"private"},deps);
assert.equal(pin.name,"Stuttgart");
assert.equal(project.pins.length,1);
assert.equal(ops.findPin(project,"p1"),pin);
assert.throws(()=>ops.createPin(project,{id:"p1",lat:1,lng:1},deps),/Duplicate/);
assert.throws(()=>ops.createPin(project,{id:"p2",lat:1,lng:1,layerId:"missing"},deps),/layer/);
assert.equal(ops.renamePin(project,"p1","  neuer Name  ",deps).name,"neuer Name");
assert.equal(ops.assignLayer(project,"p1","not-a-layer"),null);
assert.equal(pin.layerId,"private");
assert.equal(ops.assignLayer(project,"p1","layer-1"),pin);
assert.equal(pin.layerId,"layer-1");
assert.deepEqual(ops.movePin(project,"p1",{lat:48.79,lng:9.21},deps),pin);
assert.deepEqual([pin.lat,pin.lng],[48.79,9.21]);
assert.throws(()=>ops.movePin(project,"p1",{lat:91,lng:2},deps),RangeError);
assert.equal(ops.deletePin(project,"missing"),false);
assert.equal(ops.deletePin(project,"p1"),true);
assert.equal(ops.findPin(project,"p1"),null);
assert.equal(project.pins.length,0);
console.log("Pin operations: create, rename, layer assignment, move and delete verified.");
