import assert from "node:assert/strict";
import {createRequire} from "node:module";
const require=createRequire(import.meta.url);
const UIState=require("../ui/ui-state.js");
const state=new UIState();
assert.deepEqual(state.snapshot(),{selectedPinId:null,moveMode:false});
assert.throws(()=>state.enterMove(),/selected pin/);
state.selectPin("pin-1");
assert.deepEqual(state.snapshot(),{selectedPinId:"pin-1",moveMode:false});
state.enterMove();
assert.equal(state.moveMode,true);
state.leaveMove();
assert.equal(state.moveMode,false);
state.enterMove();
state.selectPin("pin-2");
assert.deepEqual(state.snapshot(),{selectedPinId:"pin-2",moveMode:false});
state.clearSelection();
assert.deepEqual(state.snapshot(),{selectedPinId:null,moveMode:false});
assert.throws(()=>state.selectPin(""),TypeError);
console.log("UI state: selection and move transitions pass");
