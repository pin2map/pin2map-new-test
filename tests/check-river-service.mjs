import assert from "node:assert/strict";
import {createRequire} from "node:module";
const require=createRequire(import.meta.url);
const RiverService=require("../application/river-service.js");
const svc=new RiverService();
await assert.rejects(()=>svc.search("Neckar"),/No river discovery/);
await assert.rejects(()=>svc.loadGeometry({id:1}),/No river geometry/);
assert.throws(()=>svc.registerDiscovery({}),TypeError);
assert.throws(()=>svc.registerGeometry({}),TypeError);
const events=[];
svc.registerDiscovery({async search(query,options){events.push(["search",query,options]);return [{id:"relation:1"}];}});
svc.registerGeometry({async load(candidate,options){events.push(["geometry",candidate,options]);return {chains:[[1,2]]};}});
const opts={signal:{cancelled:false}};
const candidates=await svc.search("Neckar",opts);
assert.deepEqual(candidates,[{id:"relation:1"}]);
const geo=await svc.loadGeometry(candidates[0],opts);
assert.deepEqual(geo,{chains:[[1,2]]});
assert.deepEqual(events,[["search","Neckar",opts],["geometry",candidates[0],opts]]);
await assert.rejects(()=>svc.search("   "),TypeError);
await assert.rejects(()=>svc.loadGeometry(null),TypeError);
console.log("Rivers: discovery and geometry independent, provider-free by default.");
